# Solicitação dos números ao usuário.
numero_1 = int(input('Digite o primeiro número inteiro: '))
numero_2 = int(input("Digite o segundo número inteiro: "))

# Atribuição à variável soma a adição dos números informados pelo usuário.
soma = numero_1 + numero_2

# Pulo de linha (apenas por estética).
print('\n')

# Resultado na tela do usuário.
print(f'Soma = {soma}')